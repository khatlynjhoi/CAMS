<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Laravel\Sanctum\HasApiTokens;

class User extends Authenticatable
{
    use HasApiTokens, HasFactory, Notifiable;

    /**
     * The attributes that are mass assignable.
     *
     * @var array<int, string>
     */
    protected $fillable = [
        'name',
        'email',
        'password',
        'role',
        'department',
        'status',
        'password_changed_at',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var array<int, string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
            'password_changed_at' => 'datetime',
        ];
    }

    /**
     * Automatically format email attribute to lowercase.
     */
    public function setEmailAttribute(string $value): void
    {
        $this->attributes['email'] = strtolower(trim($value));
    }

    /**
     * Get all audit logs generated by this user.
     */
    public function auditLogs(): HasMany
    {
        return $this->hasMany(AuditLog::class);
    }

    /**
     * Get all exam submissions recorded for this cadet.
     */
    public function examSubmissions(): HasMany
    {
        return $this->hasMany(ExamSubmission::class, 'cadet_id');
    }

    /**
     * Scope query to search by name, email, or department.
     */
    public function scopeSearch(Builder $query, string $term): Builder
    {
        return $query->where(function ($q) use ($term) {
            $q->where('name', 'like', "%{$term}%")
              ->orWhere('email', 'like', "%{$term}%")
              ->orWhere('department', 'like', "%{$term}%");
        });
    }

    /**
     * Scope query to filter users by role.
     */
    public function scopeByRole(Builder $query, string $role): Builder
    {
        return $query->where('role', $role);
    }

    /**
     * Scope query to filter active user accounts.
     */
    public function scopeActive(Builder $query): Builder
    {
        return $query->where('status', 'Active');
    }

    /**
     * Check if user possesses administrative privileges.
     */
    public function isAdmin(): bool
    {
        $role = strtolower(trim($this->role ?? ''));
        return in_array($role, ['admin', 'bma administrator']);
    }

    /**
     * Check if user is an Instructor.
     */
    public function isInstructor(): bool
    {
        return strtolower(trim($this->role ?? '')) === 'instructor';
    }

    /**
     * Check if user is a Cadet.
     */
    public function isCadet(): bool
    {
        return strtolower(trim($this->role ?? '')) === 'cadet';
    }
}